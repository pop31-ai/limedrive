#!/usr/bin/env node
"use strict";
/*
 * engine-coverage.js — builds docs/ENGINE-COVERAGE.md
 * Scans examples/player.html for handled entity types / properties,
 * cross-references with what every example game actually uses.
 */
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..");
const DIR = path.join(ROOT, "examples");
const OUT = path.join(ROOT, "docs", "ENGINE-COVERAGE.md");

const src = fs.readFileSync(path.join(DIR, "player.html"), "utf8");

function uniq(a) { return [...new Set(a)].sort(); }
function all(re) { return [...src.matchAll(re)].map(m => m[1]); }

// --- what the engine handles ---
const MOVE_PATTERNS = new Set(["adjacent", "straight", "diagonal", "any-direction", "l-shape", "forward"]);
const rawTypes = uniq([
  ...all(/\.type\s*(?:===?|!==?)\s*"([a-z_-]+)"/g),
  ...all(/"([a-z_-]+)"\s*(?:===?|!==?)\s*[a-zA-Z_$][\w$]*\.type/g),
  ...all(/case\s*"([a-z_-]+)"/g)
]);
const handledTypes = uniq(rawTypes.filter(t => !MOVE_PATTERNS.has(t)));

// properties may be read via aliases: const x = e.properties ...
const aliases = uniq(all(/(?:const|let|var)\s+([a-zA-Z_$][\w$]*)\s*=\s*[^;\n=]*\.properties\b/g));
const propSrc = new RegExp("(?:properties|" + aliases.join("|") + ")\\.([A-Za-z_$][\\w$]*)", "g");
const JS_NOISE = new Set(["length", "get", "has", "size", "keys", "values"]);
const handledProps = uniq(all(propSrc)).filter(p => !JS_NOISE.has(p));
const KNOWN_GENRES = ["platformer", "puzzle", "shooter", "rpg", "racing",
  "turn-based-strategy", "endless-runner"];
const handledModes = KNOWN_GENRES.filter(g => src.includes('"' + g + '"'));

// --- what games use ---
const games = fs.readdirSync(DIR).filter(f => f.endsWith(".json") && !f.startsWith("_")).sort();
const rows = [];
const globalUsedTypes = new Set(), globalUsedProps = new Set();
for (const f of games) {
  const g = JSON.parse(fs.readFileSync(path.join(DIR, f), "utf8").replace(/^\uFEFF/, ""));
  const types = new Map(); // type -> count
  const props = new Set();
  for (const lvl of g.levels || []) {
    for (const e of lvl.entities || []) {
      types.set(e.type, (types.get(e.type) || 0) + 1);
      for (const k of Object.keys(e.properties || {})) props.add(k);
    }
  }
  for (const t of types) globalUsedTypes.add(t[0]);
  for (const p of props) globalUsedProps.add(p);
  rows.push({ file: f, name: g.name, type: g.type, types, props });
}

// --- report ---
let md = `# Engine Coverage — что реально реализовано в player.html

_Auto-generated by \`tools/engine-coverage.js\`. Do not edit by hand._

## Как движок выбирает поведение

player.html диспетчеризует по:
- \`entity.type\` — обработанные типы (см. таблицу ниже);
- \`entity.properties.*\` — читаемые свойства;
- \`settings.type\` / режимы игры: ${handledModes.length ? handledModes.map(t => "`" + t + "`").join(", ") : "(не найдено явных проверок жанра)"}.

Массивы \`components[]\` в JSON — **декорация**: движок их не читает.
Они полезны только как документация и для будущих версий движка.

## Обработанные типы сущностей (${handledTypes.length})

${handledTypes.map(t => "- `" + t + "`").join("\n")}

## Читаемые свойства (${handledProps.length})

${handledProps.map(p => "- `" + p + "`").join("\n")}

## Матрица по играм

Легенда: ✅ тип обрабатывается движком · ⚠️ тип НЕ обрабатывается (рисует/игнорируется)

| Игра | Типов | Необрабатываемые типы | Свойства вне движка |
|------|-------|----------------------|---------------------|
`;

for (const r of rows) {
  const dead = [...r.types.keys()].filter(t => !handledTypes.includes(t));
  const deadProps = [...r.props].filter(p => !handledProps.includes(p));
  md += `| ${r.file.replace(".json", "")} (${r.type}) | ${[...r.types.keys()].length} | ` +
    (dead.length ? dead.map(t => "⚠️ `" + t + "`×" + r.types.get(t)).join(", ") : "— все живые") +
    " | " +
    (deadProps.length ? deadProps.map(p => "`" + p + "`").join(", ") : "—") +
    " |\n";
}

md += `\n## Глобально неиспользуемые движком типы из игр

${(() => { const d = [...globalUsedTypes].filter(t => !handledTypes.includes(t)); return d.length ? d.map(t => "- `" + t + "`").join("\n") : "— таких нет"; })()}

## Свойства игр, которые движок не читает

${(() => { const d = [...globalUsedProps].filter(p => !handledProps.includes(p)); return d.length ? d.map(t => "- `" + t + "`").join("\n") : "— таких нет"; })()}
`;

fs.writeFileSync(OUT, md, "utf8");
console.log(`written ${path.relative(ROOT, OUT)}`);
console.log(`engine handles: ${handledTypes.length} types, ${handledProps.length} props`);
for (const r of rows) {
  const dead = [...r.types.keys()].filter(t => !handledTypes.includes(t));
  if (dead.length) console.log(`  DEAD in ${r.file}: ${dead.join(", ")}`);
}
